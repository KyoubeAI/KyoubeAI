import type { OrgAgent, OrgState } from "../src/org/org-types.js";

type Row = [id: string, name: string, reportsTo: string | null, state?: OrgState];

/** Test agents from compact rows. Everyone is idle unless the row says otherwise. */
export function org(rows: Row[]): OrgAgent[] {
  return rows.map(([id, name, reportsTo, state]) => ({
    id,
    name,
    title: `${name} (title)`,
    icon: null,
    state: state ?? "idle",
    detail: "Idle",
    task: null,
    reportsTo,
  }));
}

